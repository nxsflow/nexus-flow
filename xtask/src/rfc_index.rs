//! The table of RFCs in `docs/rfc/README.md`, generated from the RFC files (NEX-85).
//!
//! Every RFC pull request used to add a row to a hand-kept table, so each merge left the other
//! open RFC pull requests in conflict, and the fix commit dismissed the owner's approval. The table
//! is now written by `cargo xtask rfc-index` from each `NNNN-<slug>.md` file: its number, the title
//! from its `# RFC NNNN: Title` heading, and its `Status:` line. It sits between two marker
//! comments in README.md, and `cargo xtask rfc-index --check` fails when it differs from what the
//! files say. An RFC pull request does not touch README.md; the table is regenerated on the base
//! branch, where the check runs (`factory/decisions/`, NEX-85).

use std::path::Path;

use anyhow::{anyhow, bail, Context, Result};

/// The line that opens the generated table in README.md.
pub const BEGIN: &str =
    "<!-- rfc-index: begin. Generated by `cargo xtask rfc-index` from the RFC files; do not edit. -->";
/// The line that closes it.
pub const END: &str = "<!-- rfc-index: end -->";

/// One RFC file, read.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rfc {
    pub number: String,
    pub file: String,
    pub title: String,
    pub status: String,
}

/// Every RFC file in `dir`, by number. The template (`0000-template.md`) and README.md are not RFCs.
pub fn read_rfcs(dir: &Path) -> Result<Vec<Rfc>> {
    let mut rfcs = Vec::new();
    let entries = std::fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))?;
    for entry in entries {
        let file = entry?.file_name().to_string_lossy().into_owned();
        let Some(number) = rfc_number(&file) else {
            continue;
        };
        let text =
            std::fs::read_to_string(dir.join(&file)).with_context(|| format!("reading {file}"))?;
        rfcs.push(parse(&file, number, &text)?);
    }
    rfcs.sort_by(|a, b| a.number.cmp(&b.number));
    Ok(rfcs)
}

/// `NNNN` of a file named `NNNN-<slug>.md`, unless it is the template's `0000`.
fn rfc_number(file: &str) -> Option<&str> {
    let stem = file.strip_suffix(".md")?;
    let (number, slug) = stem.split_once('-')?;
    let well_formed = number.len() == 4 && number.bytes().all(|b| b.is_ascii_digit());
    (well_formed && !slug.is_empty() && number != "0000").then_some(number)
}

/// The title from the first line, `# RFC NNNN: Title`, and the first `Status:` line.
fn parse(file: &str, number: &str, text: &str) -> Result<Rfc> {
    let heading = text.lines().next().unwrap_or_default();
    let title = heading
        .strip_prefix(&format!("# RFC {number}: "))
        .map(str::trim)
        .filter(|t| !t.is_empty())
        .with_context(|| {
            format!("{file}: the first line must be `# RFC {number}: <title>`, found `{heading}`")
        })?;
    let status = text
        .lines()
        .find_map(|l| l.strip_prefix("Status:"))
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .with_context(|| format!("{file}: no `Status:` line"))?;
    Ok(Rfc {
        number: number.to_string(),
        file: file.to_string(),
        title: title.to_string(),
        status: status.to_string(),
    })
}

/// The Markdown table for `rfcs`, header included, one row per RFC.
pub fn render(rfcs: &[Rfc]) -> String {
    let cell = |text: &str| text.replace('|', "\\|");
    let mut table = String::from("| RFC | Title | Status |\n| --- | --- | --- |\n");
    for rfc in rfcs {
        table.push_str(&format!(
            "| [{}]({}) | {} | {} |\n",
            rfc.number,
            rfc.file,
            cell(&rfc.title),
            cell(&rfc.status)
        ));
    }
    table
}

