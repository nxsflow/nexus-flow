//! The table of RFCs in `docs/rfc/README.md`, generated from the RFC files (NEX-85).
//!
//! Every RFC pull request used to add a row to a hand-kept table, so each merge left the other
//! open RFC pull requests in conflict, and the fix commit dismissed the owner's approval. The table
//! is now written by `cargo xtask rfc-index` from each `NNNN-<slug>.md` file: its number, the title
//! from its `# RFC NNNN: Title` heading, and its `Status:` line. It sits between two marker
//! comments in README.md, and `cargo xtask rfc-index --check` fails when it differs from what the
//! files say. An RFC pull request does not touch README.md; the table is regenerated on the base
//! branch, where the check runs (`factory/decisions/`, NEX-85).

