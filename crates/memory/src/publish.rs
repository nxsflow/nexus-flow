struct Output {
    success: bool,
    stdout: String,
    stderr: String,
}

enum Failure {
    NotStarted(std::io::Error),
    TimedOut(Duration),
    Io(std::io::Error),
}

impl Failure {
    fn into_error(self, what: &str) -> NxfError {
        match self {
            Failure::NotStarted(e) => NxfError::io(format!("{what} could not be started: {e}")),
            Failure::TimedOut(bound) => NxfError::io(format!(
                "{what} did not finish within {} s and was stopped; a credential helper waiting for \
                 somebody at the screen looks like this",
                bound.as_secs()
            )),
            Failure::Io(e) => NxfError::io(format!("{what}: {e}")),
        }
    }
}

/// A git call in `root` that sees this repository and asks nobody anything. Variables a hook or a
/// parent git may have set would point it at another repository or at the real index.
fn git(root: &Path, args: &[&str]) -> Command {
    let mut command = Command::new("git");
    command.current_dir(root);
    for name in [
        "GIT_DIR",
        "GIT_WORK_TREE",
        "GIT_INDEX_FILE",
        "GIT_OBJECT_DIRECTORY",
        "GIT_ALTERNATE_OBJECT_DIRECTORIES",
        "GIT_COMMON_DIR",
        "GIT_PREFIX",
    ] {
        command.env_remove(name);
    }
    command
        .env("GIT_TERMINAL_PROMPT", "0")
        .env("GCM_INTERACTIVE", "never")
        .env("GIT_OPTIONAL_LOCKS", "0")
        .args(["-c", "gc.auto=0", "-c", "core.fsmonitor=false"])
        .args(args);
    command
}

fn git_ok(root: &Path, args: &[&str], bound: Duration) -> Result<String> {
    checked(git(root, args), args, bound)
}

fn checked(command: Command, args: &[&str], bound: Duration) -> Result<String> {
    let what = format!("git {}", args.first().unwrap_or(&""));
    let out = run_bounded(command, bound).map_err(|e| e.into_error(&what))?;
    if out.success {
        Ok(out.stdout)
    } else {
        Err(NxfError::io(format!(
            "{what} failed: {}",
            out.stderr.trim()
        )))
    }
}

/// A path in the temporary directory that does not exist yet, removed when dropped. Git wants an
/// index path with no file behind it, and takes a lock next to it.
struct TempPath(PathBuf);

impl TempPath {
    fn new(name: &str) -> Self {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let n = NEXT.fetch_add(1, Ordering::Relaxed);
        Self(std::env::temp_dir().join(format!("nxm-publish-{}-{n}-{name}", std::process::id())))
    }
}

impl Drop for TempPath {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.0);
        let mut lock = self.0.clone().into_os_string();
        lock.push(".lock");
        let _ = std::fs::remove_file(lock);
    }
}

/// Run `command` to its end or to `bound`, whichever comes first; at the bound its whole process
/// group is killed. Output goes to files: see the module documentation for why not pipes.
fn run_bounded(mut command: Command, bound: Duration) -> std::result::Result<Output, Failure> {
    let stdout = TempPath::new("stdout");
    let stderr = TempPath::new("stderr");
    let open = |path: &TempPath| std::fs::File::create(&path.0).map_err(Failure::Io);
    command
        .stdin(Stdio::null())
        .stdout(open(&stdout)?)
        .stderr(open(&stderr)?);
    #[cfg(unix)]
    {
        use std::os::unix::process::CommandExt as _;
        command.process_group(0);
    }
    let mut child = command.spawn().map_err(Failure::NotStarted)?;
    let started = Instant::now();
    let status = loop {
        match child.try_wait() {
            Ok(Some(status)) => break status,
            Ok(None) if started.elapsed() >= bound => {
                kill_group(&mut child);
                let _ = child.wait();
                return Err(Failure::TimedOut(bound));
            }
            Ok(None) => std::thread::sleep(POLL),
            Err(e) => {
                kill_group(&mut child);
                let _ = child.wait();
                return Err(Failure::Io(e));
            }
        }
    };
    let read = |path: &TempPath| {
        std::fs::read(&path.0)
            .map(|bytes| String::from_utf8_lossy(&bytes).into_owned())
            .unwrap_or_default()
    };
    Ok(Output {
        success: status.success(),
        stdout: read(&stdout),
        stderr: read(&stderr),
    })
}

fn kill_group(child: &mut std::process::Child) {
    #[cfg(unix)]
    {
        // SAFETY: `kill` takes no pointers. The child was started as the leader of its own group, so
        // the negative id names that group and nothing else.
        unsafe {
            libc::kill(-(child.id() as i32), libc::SIGKILL);
        }
    }
    #[cfg(not(unix))]
    {
        let _ = child.kill();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const NOW: &str = "2026-11-06T12:00:00Z";

    fn record(published_at: Option<&str>, attempted_at: Option<&str>) -> Record {
        Record {
            published_at: published_at.map(str::to_string),
            attempted_at: attempted_at.map(str::to_string),
            ..Record::default()
        }
    }

    #[test]
    fn a_change_within_a_day_of_a_publication_waits_and_after_a_day_it_is_due() {
        let published = record(Some("2026-11-05T12:00:01Z"), Some("2026-11-05T12:00:01Z"));
        assert!(
            !is_due(&published, NOW, "changed"),
            "one second short of a day"
        );
        let published = record(Some("2026-11-05T12:00:00Z"), Some("2026-11-05T12:00:00Z"));
        assert!(is_due(&published, NOW, "changed"), "a day to the second");
    }

    #[test]
    fn nothing_changed_is_never_due_however_long_ago_the_publication_was() {
        let mut long_ago = record(Some("2026-01-01T00:00:00Z"), Some("2026-01-01T00:00:00Z"));
        long_ago.content_hash = Some(content_hash("same"));
        assert!(!is_due(&long_ago, NOW, "same"));
        assert!(is_due(&long_ago, NOW, "different"));
    }

    #[test]
    fn a_failed_attempt_is_retried_after_an_hour_not_after_a_day_and_not_at_once() {
        let mut failed = record(None, Some("2026-11-06T11:00:01Z"));
        failed.error = Some("no credentials".into());
        assert!(
            !is_due(&failed, NOW, "changed"),
            "one second short of an hour"
        );
        failed.attempted_at = Some("2026-11-06T11:00:00Z".into());
        assert!(is_due(&failed, NOW, "changed"), "an hour to the second");
    }

    #[test]
    fn a_record_nobody_can_read_holds_nothing_back() {
        let garbled = record(Some("yesterday-ish"), Some("not a stamp"));
        assert!(is_due(&garbled, NOW, "changed"));
        assert!(is_due(&Record::default(), NOW, "changed"));
    }

    #[test]
    fn credentials_in_an_address_never_reach_a_message() {
        assert_eq!(
            scrub_credentials(
                "fatal: unable to access 'https://bot:ghp_secret@github.com/a/b.git/': 403"
            ),
            "fatal: unable to access 'https://***@github.com/a/b.git/': 403"
        );
        assert_eq!(
            scrub_credentials("https://github.com/a/b.git and ssh://git@host/x"),
            "https://github.com/a/b.git and ssh://***@host/x"
        );
        assert_eq!(scrub_credentials("no address at all"), "no address at all");
    }

    #[cfg(unix)]
    #[test]
    fn a_child_past_its_bound_is_stopped_with_everything_it_started() {
        let tmp = tempfile::TempDir::new().unwrap();
        let pidfile = tmp.path().join("helper.pid");
        let script = format!("sleep 600 & echo $! > {}; wait", pidfile.display());
        let mut command = Command::new("sh");
        command.args(["-c", &script]);

        let failure = run_bounded(command, Duration::from_millis(1500));
        assert!(matches!(failure, Err(Failure::TimedOut(_))));

        // The helper is what would otherwise hold a credential dialog open for ever.
        let pid: i32 = std::fs::read_to_string(&pidfile)
            .expect("the helper started before the bound")
            .trim()
            .parse()
            .unwrap();
        let deadline = Instant::now() + Duration::from_secs(60);
        // SAFETY: signal 0 only asks whether the process exists.
        while unsafe { libc::kill(pid, 0) } == 0 {
            assert!(
                Instant::now() < deadline,
                "the helper outlived its group's kill"
            );
            std::thread::sleep(POLL);
        }
    }

    #[cfg(unix)]
    #[test]
    fn a_program_that_is_not_installed_is_told_apart_from_one_that_failed() {
        let command = Command::new("nxm-a-program-nobody-has-installed");
        assert!(matches!(
            run_bounded(command, LOCAL_BOUND),
            Err(Failure::NotStarted(e)) if e.kind() == std::io::ErrorKind::NotFound
        ));
    }
}
