//! Publishing `NEXUS_MEMORY.md`: a memory write reaches the store and nothing else, and the file
//! reaches the repository through its own pull request (6j6v.g0ye, owner decision of 2026-11-05).
//!
//! The file has to stay in git, because a machine without nexus-flow has no other way to read the
//! project's rules. But a write that regenerated it dirtied whatever checkout it ran in: the tree of
//! a running job, and from there unrelated pull requests. So the commit is built BESIDE every
//! checkout, with plumbing:
//!
//! * the origin's default branch and any open publish branch are fetched into refs of this module
//!   ([`BASE_REF`], [`OPEN_REF`]), so `FETCH_HEAD` and `origin/*` stay where the person left them,
//!   and a coder's `git rev-list HEAD..origin/main` still answers about their last fetch;
//! * the tree comes from a TEMPORARY index, so the real index is never read or written;
//! * the commit is pushed to [`BRANCH`], which belongs to this module. It is the one branch a
//!   publish moves, and it may move sideways: the commit is always rebuilt on the latest default.
//!   The push names the value it expects (`--force-with-lease`), so a racing publish fails and is
//!   retried instead of being overwritten.
//!
//! HEAD, the index, the working files and the branches of every checkout come out unchanged, and no
//! lease, claim or park is involved, because a publish works on commits. It adds objects to the
//! repository's object store and moves the two private refs.
//!
//! **A failure here is never a failed memory write.** The memory was committed long before anything
//! in this file runs. A failed attempt is kept in the [`Record`] and tried again; `nxm doc --check`
//! and `nxs sync status` say why it failed.
//!
//! **Every child is bounded and cannot ask anything.** The caller may be a service with nobody at the
//! keyboard: terminal prompts are off, and a helper that hangs on a credential dialog is killed with
//! its process group at the bound. Its output goes to files rather than pipes, because a helper that
//! outlives git would hold a pipe open and a reader would wait for it.

use crate::error::{NxfError, Result};
use crate::project_doc::{write_atomic, FILE_NAME};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{Duration, Instant};
use time::format_description::well_known::Rfc3339;
use time::OffsetDateTime;

/// The branch a publication travels on. It belongs to this module: anything pushed to it by hand is
/// replaced by the next publication.
pub const BRANCH: &str = "nxm/publish-memory";
/// Where the origin's default branch is fetched to. A private ref, so that a publish moves no
/// `origin/*` under somebody working in the checkout.
pub const BASE_REF: &str = "refs/nexus-memory/base";
/// The last publication this repository knows of: what the origin's [`BRANCH`] held when it was
/// fetched, or what this repository pushed there.
pub const OPEN_REF: &str = "refs/nexus-memory/open";
/// The record of the last attempt, in the workspace directory (`.nxs/`). Every clone that links
/// that directory shares it, as it shares the store.
pub const RECORD_FILE: &str = "memory-publish.json";

/// At most one publication per day: what a batched full CI run costs is the accepted price.
pub const PUBLISH_INTERVAL: Duration = Duration::from_secs(24 * 60 * 60);
/// How long the service waits before trying a failed attempt again. It also spaces out an attempt
/// that never reported back, so a publish that takes a while is not started twice.
pub const RETRY_INTERVAL: Duration = Duration::from_secs(60 * 60);

/// One network call: a fetch, a push or a call to the forge.
const NETWORK_BOUND: Duration = Duration::from_secs(120);
/// One local call. Generous, since a machine under load is slow rather than broken.
const LOCAL_BOUND: Duration = Duration::from_secs(60);
const POLL: Duration = Duration::from_millis(50);

const TITLE: &str = "Publish the project memory";
const BODY: &str = "Generated by `nxm doc --publish`: this pull request changes `NEXUS_MEMORY.md` \
                    and nothing else, so that it says what the project's memory store says. Do not \
                    edit it here. The next publication replaces this branch.";
const SUPERSEDED: &str = "The memory store says what the default branch says again, so merging \
                          this would take the file backwards.";

/// What a publication did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Outcome {
    /// This workspace does not publish: see [`Route::Direct`].
    NotPublished,
    /// Nothing to do: no commit was made and no pull request was opened. `pull_request` is the one
    /// already open with this content, if there is one.
    Unchanged { pull_request: Option<String> },
    /// A new pull request carries the commit.
    Opened {
        commit: String,
        pull_request: String,
    },
    /// The pull request that was already open now carries the commit.
    Updated {
        commit: String,
        pull_request: String,
    },
}

/// The pull requests of the repository's forge. A trait because a test must not reach GitHub, and
/// because an embedding host may have its own way to talk to one.
pub trait Forge {
    /// The open pull request whose head is `branch`, if there is one.
    fn open_pull_request(&self, root: &Path, branch: &str) -> Result<Option<String>>;
    /// Open a pull request from `branch` into `base`, and return its address.
    fn create_pull_request(&self, root: &Path, branch: &str, base: &str) -> Result<String>;
    /// Close a pull request that must no longer be merged.
    fn close_pull_request(&self, root: &Path, pull_request: &str) -> Result<()>;
}

/// The production forge: the `gh` found on `PATH`, signed in however that `gh` is signed in.
#[derive(Debug, Default, Clone, Copy)]
pub struct Gh;

impl Gh {
    fn run(&self, root: &Path, args: &[&str]) -> Result<String> {
        let mut command = Command::new("gh");
        command
            .args(args)
            .current_dir(root)
            .env("GH_PROMPT_DISABLED", "1")
            .env("GH_NO_UPDATE_NOTIFIER", "1");
        let out = run_bounded(command, NETWORK_BOUND).map_err(|e| match e {
            Failure::NotStarted(why) if why.kind() == std::io::ErrorKind::NotFound => {
                NxfError::io(format!(
                    "gh was not found on this PATH ({}); a pull request cannot be opened without it",
                    std::env::var("PATH").unwrap_or_default()
                ))
            }
            other => other.into_error(&format!("gh {}", args.first().unwrap_or(&""))),
        })?;
        if !out.success {
            return Err(NxfError::io(format!(
                "gh {} failed: {}",
                args.first().unwrap_or(&""),
                out.stderr.trim()
            )));
        }
        Ok(out.stdout.trim().to_string())
    }
}

impl Forge for Gh {
    fn open_pull_request(&self, root: &Path, branch: &str) -> Result<Option<String>> {
        let url = self.run(
            root,
            &[
                "pr",
                "list",
                "--head",
                branch,
                "--state",
                "open",
                "--json",
                "url",
                "--jq",
                ".[0].url // \"\"",
            ],
        )?;
        Ok((!url.is_empty()).then_some(url))
    }

    fn create_pull_request(&self, root: &Path, branch: &str, base: &str) -> Result<String> {
        let out = self.run(
            root,
            &[
                "pr", "create", "--head", branch, "--base", base, "--title", TITLE, "--body", BODY,
            ],
        )?;
        Ok(out.lines().last().unwrap_or_default().trim().to_string())
    }

    fn close_pull_request(&self, root: &Path, pull_request: &str) -> Result<()> {
        self.run(
            root,
            &["pr", "close", pull_request, "--comment", SUPERSEDED],
        )
        .map(|_| ())
    }
}

/// How the file reaches this workspace's repository.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Route {
    /// The file is written straight into the workspace: there is no `origin` to publish to, or the
    /// repository ignores the file, so no run's tree can be dirtied by it.
    Direct,
    /// A write leaves the file alone, and it reaches the repository by a publication.
    Published,
}

/// The route for the workspace at `root`.
///
/// A checkout whose git cannot be run counts as [`Route::Published`]: a file that lags costs a
/// reader a day, and a file written into somebody's tree is the failure this module exists to end.
/// That matters for the service, whose `PATH` was frozen when it was installed.
pub fn route(root: &Path) -> Route {
    let out = match run_bounded(git(root, &["remote", "get-url", "origin"]), LOCAL_BOUND) {
        Ok(out) => out,
        Err(_) if inside_a_repository(root) => return Route::Published,
        Err(_) => return Route::Direct,
    };
    if !out.success {
        return Route::Direct;
    }
    match run_bounded(
        git(root, &["check-ignore", "-q", "--", FILE_NAME]),
        LOCAL_BOUND,
    ) {
        Ok(out) if out.success => Route::Direct,
        _ => Route::Published,
    }
}

fn inside_a_repository(root: &Path) -> bool {
    root.ancestors().any(|dir| dir.join(".git").exists())
}

/// Publish `doc` for the workspace at `root`: see the module documentation. Writes no record; a
/// caller that wants one uses [`publish_recorded`].
pub fn publish(doc: &str, root: &Path, forge: &dyn Forge) -> Result<Outcome> {
    if route(root) == Route::Direct {
        return Ok(Outcome::NotPublished);
    }
    let default = default_branch(root)?;
    let branch_ref = format!("refs/heads/{BRANCH}");
    let open_tip = remote_tip(root, &branch_ref)?;

    let mut refspecs = vec![format!("+refs/heads/{default}:{BASE_REF}")];
    if open_tip.is_some() {
        refspecs.push(format!("+{branch_ref}:{OPEN_REF}"));
    }
    let mut fetch = vec![
        "fetch",
        "--quiet",
        "--no-tags",
        "--no-write-fetch-head",
        "--no-auto-gc",
        "--no-recurse-submodules",
        // Without this, git also moves `origin/<default>` whenever it fetches that branch.
        "--refmap=",
        "origin",
    ];
    fetch.extend(refspecs.iter().map(String::as_str));
    git_ok(root, &fetch, NETWORK_BOUND)?;

    let path = repository_path(root)?;
    let blob = write_blob(root, doc)?;
    let on_default = blob_at(root, BASE_REF, &path)?;
    let on_open = match open_tip {
        Some(_) => blob_at(root, OPEN_REF, &path)?,
        None => None,
    };

    if on_default.as_deref() == Some(blob.as_str()) {
        // Nothing to say that the default does not say. No branch is left over, so no forge is
        // needed either: a workspace with no `gh` is not told about a tool it does not need.
        if open_tip.is_some() {
            if let Some(pull_request) = forge.open_pull_request(root, BRANCH)? {
                forge.close_pull_request(root, &pull_request)?;
            }
        }
        return Ok(Outcome::Unchanged { pull_request: None });
    }

    // Asked BEFORE the push, so that a forge which cannot be reached leaves no branch behind.
    let open_pull_request = forge.open_pull_request(root, BRANCH)?;
    if on_open.as_deref() == Some(blob.as_str()) && open_pull_request.is_some() {
        return Ok(Outcome::Unchanged {
            pull_request: open_pull_request,
        });
    }

    let commit = build_commit(root, &path, &blob)?;
    let lease = format!(
        "--force-with-lease={branch_ref}:{}",
        open_tip.as_deref().unwrap_or("")
    );
    // To the address, not to the name: a push to `origin` would also create
    // `origin/nxm/publish-memory` in the checkout's remote-tracking refs. No hook runs either, since
    // a repository's pre-push hook is about its code and may well start its tests.
    let url = git_ok(
        root,
        &["remote", "get-url", "--push", "origin"],
        LOCAL_BOUND,
    )?;
    git_ok(
        root,
        &[
            "push",
            "--quiet",
            "--no-verify",
            &lease,
            url.trim(),
            &format!("{commit}:{branch_ref}"),
        ],
        NETWORK_BOUND,
    )?;
    git_ok(root, &["update-ref", OPEN_REF, &commit], LOCAL_BOUND)?;

    Ok(match open_pull_request {
        Some(pull_request) => Outcome::Updated {
            commit,
            pull_request,
        },
        None => Outcome::Opened {
            pull_request: forge.create_pull_request(root, BRANCH, &default)?,
            commit,
        },
    })
}

/// The commit carrying `blob` at `path`, on [`BASE_REF`], built through a temporary index.
fn build_commit(root: &Path, path: &str, blob: &str) -> Result<String> {
    let index = TempPath::new("index");
    let with_index = |args: &[&str]| -> Result<String> {
        let mut command = git(root, args);
        command.env("GIT_INDEX_FILE", &index.0);
        checked(command, args, LOCAL_BOUND)
    };
    with_index(&["read-tree", BASE_REF])?;
    let entry = format!("100644,{blob},{path}");
    with_index(&["update-index", "--add", "--cacheinfo", &entry])?;
    let tree = with_index(&["write-tree"])?;

    let args = ["commit-tree", tree.trim(), "-p", BASE_REF, "-m", TITLE];
    let mut command = git(root, &args);
    // A service has whatever identity its home gives it, which may be none.
    let identified = run_bounded(git(root, &["var", "GIT_COMMITTER_IDENT"]), LOCAL_BOUND)
        .map(|out| out.success)
        .unwrap_or(false);
    if !identified {
        for (name, value) in [
            ("GIT_AUTHOR_NAME", "nexus-memory"),
            ("GIT_AUTHOR_EMAIL", "nexus-memory@users.noreply.github.com"),
            ("GIT_COMMITTER_NAME", "nexus-memory"),
            (
                "GIT_COMMITTER_EMAIL",
                "nexus-memory@users.noreply.github.com",
            ),
        ] {
            command.env(name, value);
        }
    }
    checked(command, &args, LOCAL_BOUND).map(|commit| commit.trim().to_string())
}

/// The origin's default branch, as the origin says it now.
fn default_branch(root: &Path) -> Result<String> {
    let out = git_ok(
        root,
        &["ls-remote", "--symref", "origin", "HEAD"],
        NETWORK_BOUND,
    )?;
    out.lines()
        .find_map(|line| {
            line.strip_prefix("ref: refs/heads/")?
                .split_whitespace()
                .next()
                .map(str::to_string)
        })
        .ok_or_else(|| {
            NxfError::io("the origin names no default branch, so there is nothing to publish onto")
        })
}

fn remote_tip(root: &Path, full_ref: &str) -> Result<Option<String>> {
    let out = git_ok(root, &["ls-remote", "origin", full_ref], NETWORK_BOUND)?;
    Ok(out.split_whitespace().next().map(str::to_string))
}

/// Where the file sits in the repository: the workspace may be a subdirectory of it.
fn repository_path(root: &Path) -> Result<String> {
    let prefix = git_ok(root, &["rev-parse", "--show-prefix"], LOCAL_BOUND)?;
    Ok(format!("{}{FILE_NAME}", prefix.trim()))
}

fn write_blob(root: &Path, doc: &str) -> Result<String> {
    let file = TempPath::new("doc");
    std::fs::write(&file.0, doc)
        .map_err(|e| NxfError::io(format!("writing {}: {e}", file.0.display())))?;
    let path = file.0.display().to_string();
    git_ok(
        root,
        &["hash-object", "-w", "--no-filters", &path],
        LOCAL_BOUND,
    )
    .map(|blob| blob.trim().to_string())
}

/// The blob `reference` holds at `path`, if it holds one.
fn blob_at(root: &Path, reference: &str, path: &str) -> Result<Option<String>> {
    let spec = format!("{reference}:{path}");
    let out = run_bounded(
        git(root, &["rev-parse", "--verify", "--quiet", &spec]),
        LOCAL_BOUND,
    )
    .map_err(|e| e.into_error("git rev-parse"))?;
    Ok(out.success.then(|| out.stdout.trim().to_string()))
}

/// Whether this checkout's copy of the file is something that was published, read from this
/// repository alone: no network, so `nxm doc --check` stays a local question.
///
/// "Published" means it stands in the file's history on the default branch, or on [`OPEN_REF`]. Git
/// is the record on purpose. A checkout may lag by any number of publications, and it may have been
/// written on another device, so a single remembered hash would call both of them hand edits.
///
/// What this cannot see: a hand edit that was reviewed and MERGED into the default branch. It stands
/// in that history like any publication. The next publication replaces it, within a day and in a
/// pull request where the removal is visible, because the store's projection differs from it.
pub fn is_published_copy(root: &Path) -> Result<bool> {
    let path = repository_path(root)?;
    let local = git_ok(root, &["hash-object", "--", FILE_NAME], LOCAL_BOUND)?;
    let local = local.trim();
    for reference in known_refs(root) {
        if blob_at(root, &reference, &path)?.as_deref() == Some(local) {
            return Ok(true);
        }
    }
    for reference in default_refs(root) {
        // Every version the file ever had there, in one call. `-m` for the merges, and the tips are
        // asked above because a shallow clone's only commit shows no change at all.
        let out = git_ok(
            root,
            &[
                "log",
                "--raw",
                "--no-abbrev",
                "--no-renames",
                "-m",
                "--format=",
                &reference,
                "--",
                &path,
            ],
            LOCAL_BOUND,
        )?;
        let found = out
            .lines()
            .any(|line| line.split_whitespace().nth(3) == Some(local));
        if found {
            return Ok(true);
        }
    }
    Ok(false)
}

/// Whether the default branch, as this repository last saw it, carries the file at all.
pub fn default_carries_the_file(root: &Path) -> Result<bool> {
    let path = repository_path(root)?;
    for reference in default_refs(root) {
        if blob_at(root, &reference, &path)?.is_some() {
            return Ok(true);
        }
    }
    Ok(false)
}

fn known_refs(root: &Path) -> Vec<String> {
    let mut refs = default_refs(root);
    if blob_ref_exists(root, OPEN_REF) {
        refs.push(OPEN_REF.to_string());
    }
    refs
}

/// The refs that say what the default branch is, without asking the origin.
fn default_refs(root: &Path) -> Vec<String> {
    let mut refs = Vec::new();
    if blob_ref_exists(root, BASE_REF) {
        refs.push(BASE_REF.to_string());
    }
    let named = run_bounded(
        git(root, &["symbolic-ref", "-q", "refs/remotes/origin/HEAD"]),
        LOCAL_BOUND,
    )
    .ok()
    .filter(|out| out.success)
    .map(|out| out.stdout.trim().to_string());
    if let Some(named) = named {
        refs.push(named);
    } else {
        refs.extend(
            ["refs/remotes/origin/main", "refs/remotes/origin/master"]
                .into_iter()
                .filter(|r| blob_ref_exists(root, r))
                .map(str::to_string),
        );
    }
    refs
}

fn blob_ref_exists(root: &Path, reference: &str) -> bool {
    run_bounded(
        git(root, &["rev-parse", "--verify", "--quiet", reference]),
        LOCAL_BOUND,
    )
    .map(|out| out.success)
    .unwrap_or(false)
}

// ---- the record --------------------------------------------------------------------------------

/// What the last attempts did, kept beside the store. It answers two questions: is another
/// publication due, and why did the last one fail. It is local state and says nothing about the
/// memories themselves, so a lost file costs one no-op publication.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Record {
    /// When an attempt was last made or started.
    pub attempted_at: Option<String>,
    /// When a publication last changed something on the origin. A no-op does not count.
    pub published_at: Option<String>,
    /// The hash of the content the last successful attempt found published.
    pub content_hash: Option<String>,
    pub commit: Option<String>,
    pub pull_request: Option<String>,
    /// Why the last attempt failed, or `None` when it did not.
    pub error: Option<String>,
}

/// The record in the workspace directory `ws_dir`, or an empty one. An unreadable record reads as
/// empty: the worst that does is one more attempt, which finds nothing to do.
pub fn read_record(ws_dir: &Path) -> Record {
    std::fs::read(ws_dir.join(RECORD_FILE))
        .ok()
        .and_then(|bytes| serde_json::from_slice(&bytes).ok())
        .unwrap_or_default()
}

pub fn write_record(ws_dir: &Path, record: &Record) -> Result<()> {
    let bytes = serde_json::to_vec_pretty(record).expect("the record serializes");
    write_atomic(&ws_dir.join(RECORD_FILE), &bytes)
}

/// The hash a [`Record`] keeps of a document.
pub fn content_hash(doc: &str) -> String {
    Sha256::digest(doc.as_bytes())
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// Whether the clock allows an attempt: a day since the last publication, and an hour since the last
/// attempt. Asked first by the service, because it needs no store and no git. A stamp that cannot be
/// read does not hold anything back.
pub fn clock_allows(record: &Record, now: &str) -> bool {
    let waited = |stamp: &Option<String>, interval: Duration| match stamp
        .as_deref()
        .map(|s| OffsetDateTime::parse(s, &Rfc3339))
    {
        Some(Ok(then)) => match OffsetDateTime::parse(now, &Rfc3339) {
            Ok(now) => now - then >= interval,
            Err(_) => true,
        },
        _ => true,
    };
    waited(&record.published_at, PUBLISH_INTERVAL) && waited(&record.attempted_at, RETRY_INTERVAL)
}

/// Whether the service should publish: the clock allows it, and something changed.
pub fn is_due(record: &Record, now: &str, doc: &str) -> bool {
    clock_allows(record, now) && record.content_hash.as_deref() != Some(&*content_hash(doc))
}

/// [`publish`], with the attempt kept in the record of `ws_dir`. The manual path and the service's
/// job both come through here; neither asks the clock here, because a person who runs the verb means
/// it and the service has already asked.
pub fn publish_recorded(
    doc: &str,
    ws_dir: &Path,
    root: &Path,
    now: &str,
    forge: &dyn Forge,
) -> Result<Outcome> {
    let result = publish(doc, root, forge);
    if matches!(result, Ok(Outcome::NotPublished)) {
        return result;
    }
    let mut record = read_record(ws_dir);
    record.attempted_at = Some(now.to_string());
    let result = match result {
        Ok(outcome) => {
            record.error = None;
            record.content_hash = Some(content_hash(doc));
            match &outcome {
                Outcome::Opened {
                    commit,
                    pull_request,
                }
                | Outcome::Updated {
                    commit,
                    pull_request,
                } => {
                    record.published_at = Some(now.to_string());
                    record.commit = Some(commit.clone());
                    record.pull_request = Some(pull_request.clone());
                }
                Outcome::Unchanged { pull_request } => {
                    record.pull_request = pull_request.clone();
                }
                Outcome::NotPublished => {}
            }
            Ok(outcome)
        }
        Err(mut e) => {
            e.msg = scrub_credentials(&e.msg);
            record.error = Some(e.msg.clone());
            Err(e)
        }
    };
    if let Err(e) = write_record(ws_dir, &record) {
        return match result {
            // The publication stands, and only the memory of it is lost: the next attempt finds
            // nothing to do and writes the record again. That is worth saying but is no failure.
            Ok(outcome) => {
                eprintln!(
                    "note: {} could not be written ({}); the publication itself went through",
                    RECORD_FILE, e.msg
                );
                Ok(outcome)
            }
            Err(failed) => Err(failed),
        };
    }
    result
}

/// `https://user:token@host/…` becomes `https://***@host/…`. Git quotes the origin's address in its
/// errors, and those errors end up in a record, in a log and on a terminal.
pub fn scrub_credentials(message: &str) -> String {
    let mut out = String::with_capacity(message.len());
    let mut rest = message;
    while let Some(at) = rest.find("://") {
        let (before, after) = rest.split_at(at + 3);
        out.push_str(before);
        let authority_end = after
            .find(|c: char| c == '/' || c.is_whitespace() || c == '\'' || c == '"')
            .unwrap_or(after.len());
        match after[..authority_end].rfind('@') {
            Some(userinfo_end) => {
                out.push_str("***");
                rest = &after[userinfo_end..];
            }
            None => rest = after,
        }
    }
    out.push_str(rest);
    out
}

