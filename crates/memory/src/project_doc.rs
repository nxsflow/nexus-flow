    #[test]
    fn an_unchanged_document_reports_unchanged_even_mid_rebase() {
        // PR #287 review, Test Quality #3: the order of the two guards is a deliberate claim —
        // "nothing changed" is checked BEFORE "the worktree is busy", because when there is
        // nothing to write there is nothing to hold back, and `Unchanged` is the truthful answer.
        // Without this pairing the ordering could silently invert and no test would notice.
        let tmp = TempDir::new().unwrap();
        let git = git_worktree(tmp.path());
        let mut s = store();
        remember(&mut s, "auth", "auth uses JWT, not sessions");
        let path = match regenerate(&s, tmp.path()).unwrap() {
            Outcome::Written(p) => p,
            other => panic!("expected the first write, got {other:?}"),
        };

        std::fs::create_dir_all(git.join("rebase-merge")).unwrap();
        assert_eq!(
            regenerate(&s, tmp.path()).unwrap(),
            Outcome::Unchanged(path),
            "a rebase does not turn an idle no-op into a held-back write"
        );
    }

    #[test]
    fn regenerating_touches_nothing_inside_the_git_directory() {
        // PR #287 review, Test Quality #4: "never commit" was satisfied only by omission — no test
        // would have caught a future change that staged or committed the file. Committing is not
        // something this module can do without writing under `.git` (index, objects, refs, logs),
        // so the invariant is pinned as "the git directory comes out byte-identical".
        let tmp = TempDir::new().unwrap();
        let git = git_worktree(tmp.path());
        std::fs::write(git.join("HEAD"), b"ref: refs/heads/main\n").unwrap();
        std::fs::create_dir_all(git.join("objects")).unwrap();
        std::fs::write(git.join("index"), b"fake index").unwrap();

        let before = snapshot(&git);
        let mut s = store();
        remember(&mut s, "auth", "auth uses JWT, not sessions");
        assert!(matches!(
            regenerate(&s, tmp.path()).unwrap(),
            Outcome::Written(_)
        ));
        assert!(
            tmp.path().join(FILE_NAME).is_file(),
            "the file itself landed"
        );
        assert_eq!(
            before,
            snapshot(&git),
            "the change belongs to the human: nothing is staged, nothing is committed"
        );
    }

    /// Every path under `dir` with its bytes — enough to notice a staged index, a new object, or a
    /// moved ref.
    fn snapshot(dir: &Path) -> Vec<(PathBuf, Vec<u8>)> {
        fn walk(dir: &Path, out: &mut Vec<(PathBuf, Vec<u8>)>) {
            let mut entries: Vec<_> = std::fs::read_dir(dir)
                .unwrap()
                .map(|e| e.unwrap().path())
                .collect();
            entries.sort();
            for path in entries {
                if path.is_dir() {
                    out.push((path.clone(), Vec::new()));
                    walk(&path, out);
                } else {
                    out.push((path.clone(), std::fs::read(&path).unwrap()));
                }
            }
        }
        let mut out = Vec::new();
        walk(dir, &mut out);
        out
    }

