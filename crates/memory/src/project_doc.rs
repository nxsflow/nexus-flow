    /// A worktree whose `.git` is a real directory (the ordinary clone).
    fn git_worktree(root: &Path) -> PathBuf {
        let git = root.join(".git");
        std::fs::create_dir_all(&git).unwrap();
        git
    }

    #[test]
    fn a_worktree_in_the_middle_of_an_operation_is_left_alone() {
        // Rule (c): a background daemon must not drop an unrelated file into a worktree somebody
        // is rebasing. Table-driven over every marker, since missing ONE of them is the whole risk.
        for (marker, name) in GIT_OPERATIONS {
            let tmp = TempDir::new().unwrap();
            let git = git_worktree(tmp.path());
            let mut s = store();
            remember(&mut s, "auth", "auth uses JWT, not sessions");

            // Directory markers (`rebase-merge/`) and file markers (`MERGE_HEAD`) both exist; a
            // directory works for either, since the guard only asks whether the path is there.
            std::fs::create_dir_all(git.join(marker)).unwrap();

            assert_eq!(
                regenerate(&s, tmp.path()).unwrap(),
                Outcome::Skipped(Skip::WorktreeBusy(name)),
                "{marker} must hold the write back"
            );
            assert!(
                !tmp.path().join(FILE_NAME).exists(),
                "{marker}: nothing was written"
            );
        }
    }

