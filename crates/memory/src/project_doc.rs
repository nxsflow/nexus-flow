//! `NEXUS_MEMORY.md` — the project-memory document as a BUILD PRODUCT (6j6v.8q88).
//!
//! Since the reach of a memory decides where it surfaces (6j6v.srpg), everything a hand-maintained
//! context document used to hold is simply a memory with reach `project`. So the document stops
//! being a source and becomes a **projection**: `nxm` is the one source of truth, this file is its
//! rendering, and git supplies the version history the store does not have — with the diff visible
//! in the change proposal. The precedent is `AGENTS.md`, already a generated context file nobody
//! may edit by hand; this carries the pattern to its end.
//!
//! Two readers justify the file's existence, and both explain its shape:
//!
//! * A contributor with no nexus-flow installed. Exactly one wired SessionStart hook carries a
//!   `|| cat NEXUS_MEMORY.md` tail (the first the assembler wires — Ruling R1, nxf a2a1), so this
//!   file is the fallback path. *(It was a single `nxs prime || cat NEXUS_MEMORY.md` hook until
//!   nxf n2m6 + a2a1 split the wiring one-per-module; the tail moved onto the first entry rather
//!   than onto all of them, so the file still arrives exactly once.)*
//! * Somebody reading the repository on a forge, where no hook runs at all.
//!
//! **Two halves since 6j6v.xbnh, and the notice between them is the point** (owner decision of
//! 2026-08-27). The file opens with the SAME index `nxm prime` replays, under a notice saying that
//! this half is already in the session's context — because the incident that opened that ticket was
//! an agent reading this file top to bottom while `nxs prime` sat in the SessionStart hook. Below
//! the notice the full bodies remain, and that is deliberate too: the file is the versioned,
//! diff-able record of what the memories SAY, so a change to a memory stays visible in a change
//! proposal. An index-only file would move every body into sqlite alone and out of every diff.
//!
//! The index half is therefore a strict subset of `prime` (it is the same renderer over the same
//! set); the full-text half is what `nxm recall <key>` serves, and the notice tells a reader to
//! read it the same way — one memory at a time, on purpose.
//!
//! **Generation is a side effect of writing, never a command someone must remember to run**
//! ([`regenerate`]): every `nxm` write regenerates it, and so does a sync pass that pulled new ops
//! (`nxs sync daemon`). Deliberately NOT at `prime`: a session start only heals the file once
//! somebody opens the project, so a repository resting for two weeks would show a two-week-old
//! state to precisely the reader the file exists for. `prime` itself reads `nxm` directly and is
//! never stale.
//!
//! Because a background daemon now writes a VERSIONED file inside somebody else's git worktree
//! while they work in it, [`regenerate`] holds three rules: write only when the content actually
//! differs (so the normal case is no write at all), never commit (the change is unstaged and
//! belongs to the human), and stand down entirely while the worktree is mid-operation — a rebase,
//! a merge, a conflict resolution ([`git_operation_in_progress`]).

use crate::error::{NxfError, Result};
