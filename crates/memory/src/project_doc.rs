use std::path::{Path, PathBuf};

/// The generated file's name, at the workspace root (next to `AGENTS.md`, the other generated
/// context file).
pub const FILE_NAME: &str = "NEXUS_MEMORY.md";

/// The header every generated copy carries. Two audiences, deliberately: the HTML comment marks the
/// file as managed for a tool or a reviewer skimming the diff, and the visible blockquote tells a
/// human who opened it on a forge where the text really comes from and how to change it. Without
/// the second one the file looks like ordinary documentation, somebody edits it, and source and
/// projection drift — the same failure class as a frozen copy whose header still claims to be
/// interim four releases later.
const HEADER: &str = "<!-- generated by nexus-flow — do not edit; run `nxm remember` instead -->\n\
                      # Project memory\n\n\
                      > **Generated file — do not edit.** Every entry below is a memory in this \
                      project's `nxm` store, projected here so the context survives without \
                      nexus-flow installed. Change it with `nxm remember` / `nxm forget`; an edit \
                      made here is overwritten by the next write. `nxm doc --check` reports drift.";

/// The notice that separates the two halves, and the reason the file is not simply read top to
/// bottom (6j6v.xbnh).
///
/// It is the direct answer to the incident that opened that ticket: an agent whose SessionStart
/// hook had ALREADY delivered the index opened this file and read all of it by hand. A notice that
/// only said "this is generated" would not have stopped it — what stops it is naming which half it
/// already has and how the other half is meant to be read.
///
/// **Corrected 2026-08-28 (nxf n2m6 + a2a1): it named `nxs prime`.** The notice said the index was
/// "the same one `nxs prime` replays at session start", which was exact while `nxs prime` WAS the
/// SessionStart hook. It is one hook per active module now, so what replays this index at session
/// start is `nxm prime`; `nxs prime` still replays it when a person runs that verb by hand. The
/// point of the sentence is to tell the reader they already hold this — naming a command that no
/// longer runs at session start would undercut exactly that.
///
/// **Corrected 2026-08-29 (nxf 6j6v.5jm3): "the same one" became conditionally false.** The block's
/// index is bounded now ([`facade::PRIME_BLOCK_BUDGET_BYTES`]) while this document's is not — it is
/// the versioned record of what the workspace knows, and a record that dropped entries to fit a
/// host's hook limit would be a worse artifact, not a smaller one. So in a large workspace the two
/// indexes genuinely differ, and a notice claiming they are the same would send a reader past
/// exactly the lines a session start could not hand them.
///
/// The sentence therefore states the relationship rather than an equality — you hold all of it or
/// its leading part — and names `nxm index`, which is the other place the whole of it is served.
/// Both halves of the notice's job survive: it still says which half the reader already has, and it
/// still says the full text below is read one memory at a time.
const READ_ME_FIRST: &str =
    "> **You have already been given the index below** — all of it, or as much of it as a session \
     start could carry. It is the same index `nxm prime` replays, which stops at the byte budget \
     the host delivers and says so when it does (`nxm index` prints the whole of it), so there is \
     nothing to gain by reading it again here. Underneath it stands the FULL TEXT of each memory — \
     that is what `nxm recall <key>` serves, and it is meant to be read one memory at a time, when \
     the index tells you a particular one matters. Reading this file end to end is the expensive \
     way to obtain what you already have.";

/// What [`regenerate`] did — a value rather than a printed line, because the callers differ wildly:
/// the CLI stays silent (the file shows up in `git status`), the sync daemon logs, and a test
/// asserts.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Outcome {
    /// The file was created or rewritten (the content genuinely changed).
    Written(PathBuf),
    /// The file is already byte-identical to the projection — the steady state, and the common
    /// case for a daemon pass.
    Unchanged(PathBuf),
    /// Nothing was written, and why. Never an error: each reason is a legitimate state.
    Skipped(Skip),
}

/// Why [`regenerate`] wrote nothing.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Skip {
    /// There is no file yet and no memory to project into one. A workspace that has never
    /// remembered anything does not get an empty document planted in its root; once the file
    /// EXISTS it is kept accurate, empty state included, so it can never quietly lie.
    NothingToProject,
    /// The git worktree is mid-operation (the named one: `rebase`, `merge`, …). Writing an
    /// unrelated file into a worktree somebody is rebasing is how a background process turns a
    /// tricky moment into a confusing one.
    WorktreeBusy(&'static str),
}

/// Render the projection for `store` — the exact bytes the file should hold.
///
/// Both halves come from `prime`'s own set and `prime`'s own renderers, so neither can drift from
/// the session start: the index is [`facade::render_memory_index`] (byte for byte what a session is
/// handed) and the full text below it is [`facade::render_memory_blocks`]. Item-scoped memories that
/// name board items are left out here for the same reason they are left out of `prime` — they read
/// where a reader is already looking.
pub fn render(store: &MemoryStore) -> Result<String> {
    let report = facade::prime(store)?;
    Ok(render_report(&report))
}

/// [`render`] over an already-computed report — the pure half, so a caller that already holds a
/// [`PrimeReport`](facade::PrimeReport) (the subset proof, for one) does not read the store twice.
pub fn render_report(report: &facade::PrimeReport) -> String {
    format!("{HEADER}\n\n{}\n", body_of(report))
}

/// The part of the document that comes from the store: the index, the notice, and the full bodies
/// beneath — or `prime`'s own empty-state sentence when there is nothing to project (6j6v.xbnh).
///
/// The two halves are separated by a heading rather than only by prose, so a reader skimming the
/// outline sees where the index stops and the full text begins.
fn body_of(report: &facade::PrimeReport) -> String {
    if report.memories.is_empty() {
        return facade::PRIME_NO_MEMORIES.to_string();
    }
    let mut parts = vec![
        READ_ME_FIRST.to_string(),
        format!("## Index ({})", report.memories.len()),
        facade::render_memory_index(&report.memories),
    ];
    parts.extend(report.introduction_gap());
    parts.push("## Full text".to_string());
    parts.push(facade::render_memory_blocks(&report.memories));
    parts.join("\n\n")
}

/// Regenerate `<root>/NEXUS_MEMORY.md` from `store`. The one write path — every trigger (an `nxm`
/// write, a sync pass that pulled ops) calls exactly this, so the three worktree rules cannot be
/// implemented twice and drift apart.
///
/// Never fails just because there is nothing to do: a no-op is an [`Outcome`], not an error. A
/// genuine IO failure IS an error, because a file this one silently failed to write is precisely
/// the stale context the drift check exists to catch.
pub fn regenerate(store: &MemoryStore, root: &Path) -> Result<Outcome> {
    let path = root.join(FILE_NAME);
    let current = match std::fs::read_to_string(&path) {
        Ok(s) => Some(s),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => {
            return Err(NxfError::io(format!(
                "reading {} to compare it with the memory store: {e}",
                path.display()
            )))
        }
    };
    // ONE read of the store per call (PR #287 review, Code Quality #1): the report answers both
    // "what should the file say" and "is there anything to say at all", and this path runs on every
    // single memory write.
    let report = facade::prime(store)?;
    let target = render_report(&report);

    // An untouched workspace stays untouched: no file and nothing to say means no file.
    if current.is_none() && report.memories.is_empty() {
        return Ok(Outcome::Skipped(Skip::NothingToProject));
    }
    // The normal case, checked BEFORE the worktree guard on purpose: when nothing changed there is
    // nothing to suspend, and reporting `Unchanged` during a rebase is more truthful than
    // reporting that a write was held back.
    if current.as_deref() == Some(target.as_str()) {
        return Ok(Outcome::Unchanged(path));
    }
    if let Some(op) = git_operation_in_progress(root) {
        return Ok(Outcome::Skipped(Skip::WorktreeBusy(op)));
    }

    write_atomic(&path, target.as_bytes())?;
    Ok(Outcome::Written(path))
}

/// How the file on disk compares with the store — what `nxm doc --check` reports.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Drift {
    /// The file matches the projection byte for byte.
    InSync,
    /// The file exists and does NOT match: it was edited by hand, or a write that should have
    /// regenerated it never ran (a daemon that was not running here is exactly this case, which is
    /// what turns that failure from silent into loud).
    Drifted,
    /// The store has memories to project but no file exists.
    Missing,
    /// No file, and nothing to project into one — the untouched workspace, in sync trivially.
    NotApplicable,
}

impl Drift {
    /// Whether this is a state the check should go red on.
    pub fn is_drift(&self) -> bool {
        matches!(self, Drift::Drifted | Drift::Missing)
    }

    pub fn as_str(&self) -> &'static str {
        match self {
            Drift::InSync => "in_sync",
            Drift::Drifted => "drifted",
            Drift::Missing => "missing",
            Drift::NotApplicable => "not_applicable",
        }
    }
}

/// Compare `<root>/NEXUS_MEMORY.md` with the projection of `store`, without writing anything.
pub fn check(store: &MemoryStore, root: &Path) -> Result<Drift> {
    let path = root.join(FILE_NAME);
    // One read of the store here too — same reason as in [`regenerate`].
    let report = facade::prime(store)?;
    let target = render_report(&report);
    match std::fs::read_to_string(&path) {
        Ok(current) if current == target => Ok(Drift::InSync),
        Ok(_) => Ok(Drift::Drifted),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            if report.memories.is_empty() {
                Ok(Drift::NotApplicable)
            } else {
                Ok(Drift::Missing)
            }
        }
        Err(e) => Err(NxfError::io(format!(
            "reading {} to compare it with the memory store: {e}",
            path.display()
        ))),
    }
}

// ---- the git worktree guard -------------------------------------------------------------------

/// The mid-operation markers git leaves in the gitdir, each with the name to report. Order is
/// report order only — any one of them means "stand down".
const GIT_OPERATIONS: &[(&str, &str)] = &[
    ("rebase-merge", "rebase"),
    ("rebase-apply", "rebase"),
    ("MERGE_HEAD", "merge"),
    ("CHERRY_PICK_HEAD", "cherry-pick"),
    ("REVERT_HEAD", "revert"),
    ("BISECT_LOG", "bisect"),
];

/// The operation `root`'s git worktree is in the middle of, or `None` when it is idle (or is not a
/// git worktree at all — an unversioned workspace has nothing to protect).
///
/// Reads the markers directly instead of shelling out to `git`: the check runs on every memory
/// write and on every daemon pass, the marker layout is git's own stable on-disk contract, and a
/// file-based check is testable without a git binary. The `.git` entry is followed when it is a
/// FILE (`gitdir: …`) rather than a directory, which is the linked-worktree and submodule case —
/// and precisely the case that matters, since each linked worktree keeps its OWN rebase/merge
/// state in its own gitdir.
pub fn git_operation_in_progress(root: &Path) -> Option<&'static str> {
    let git_dir = resolve_git_dir(root)?;
    GIT_OPERATIONS
        .iter()
        .find(|(marker, _)| git_dir.join(marker).exists())
        .map(|(_, name)| *name)
}

/// The gitdir for the worktree at `root`: `<root>/.git` when that is a directory, else the path its
/// `gitdir: <path>` pointer names (relative paths resolve against `root`, as git writes them).
fn resolve_git_dir(root: &Path) -> Option<PathBuf> {
    let dot_git = root.join(".git");
    if dot_git.is_dir() {
        return Some(dot_git);
    }
    let pointer = std::fs::read_to_string(&dot_git).ok()?;
    let target = pointer
        .lines()
        .find_map(|l| l.trim().strip_prefix("gitdir:"))?;
    let target = Path::new(target.trim());
    Some(if target.is_absolute() {
        target.to_path_buf()
    } else {
        root.join(target)
    })
}

// ---- the atomic writer ------------------------------------------------------------------------

/// Write `contents` to `path` atomically: a sibling temp opened `O_EXCL`, then a same-directory
/// rename over the target. Two reasons, both real here: a reader (an agent whose SessionStart hook
/// just `cat`ted this file) never sees a half-written document, and a symlink squatting on the
/// PREDICTABLE temp path is refused rather than followed.
///
/// A local copy of the idiom `nxs`'s registry/heartbeat writers use, because theirs is
/// `pub(crate)` in another crate. Kept deliberately short and identical in shape so the two read as
/// the same routine.
fn write_atomic(path: &Path, contents: &[u8]) -> Result<()> {
    use std::io::Write as _;
    let dir = path.parent().unwrap_or_else(|| Path::new("."));
    let name = path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or(FILE_NAME);
    let tmp = dir.join(format!(".{name}.nxm.tmp.{}", std::process::id()));
    let write = || -> std::io::Result<()> {
        let mut f = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&tmp)?;
        f.write_all(contents)?;
        f.sync_all()
    };
    write()
        .and_then(|()| std::fs::rename(&tmp, path))
        .map_err(|e| {
            let _ = std::fs::remove_file(&tmp); // best-effort: never strand the temp sibling
            NxfError::io(format!("writing {}: {e}", path.display()))
        })
}

